const TABLES: Readonly<Record<LanguageCode, Readonly<Record<TextKey, string>>>> = {
  'zh-Hans': zhHans,
  'zh-Hant': zhHant,
  en,
  ja,
};

export const TEXT_KEYS = Object.keys(zhHans) as TextKey[];

export function translate(language: LanguageCode, key: TextKey): string {
  return TABLES[language][key];
}

export function isLanguageCode(value: string | null | undefined): value is LanguageCode {
  return value === 'zh-Hans' || value === 'zh-Hant' || value === 'en' || value === 'ja';
}

export function resolveLanguage(saved: string | null, systemLocale: string): LanguageCode {
  if (isLanguageCode(saved)) {
    return saved;
  }
  const locale = systemLocale.toLowerCase().replace(/_/g, '-');
  if (locale.startsWith('zh')) {
    return /hant|-tw|-hk|-mo/.test(locale) ? 'zh-Hant' : 'zh-Hans';
  }
  if (locale.startsWith('ja')) {
    return 'ja';
  }
  return 'en';
}